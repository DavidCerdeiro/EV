from fastapi import APIRouter
from app.services.chat_service import response_to_user
from app.schemas.chat_schema import ChatRequest, ChatResponse

router = APIRouter(prefix="/chat", tags=["chat"])

@router.post(
    "/response", 
    response_model=ChatResponse,
    summary="Obtain a response from the AI assistant based on the user's message",
    response_description="The response generated by the chat service"
)
async def get_response(chatRequest: ChatRequest):
    """
    Processes the user's message through the AI assistant and returns a structured response.
    
    **Parameters:**
    - **chatRequest**: Object that contains the original user message.
    
    **Returns:**
    - An object `ChatResponse` with the response ready to be displayed.
    """
    chat_response = response_to_user(user_message=chatRequest.user_message)
    return chat_response